export const DONT_KNOW = 'Не знаю';
export const OTHER = 'Другое';

const str = (a: Answers, id: string): string => {
  const v = a[id]?.value;
  return typeof v === 'string' ? v : '';
};

const multiHas = (a: Answers, id: string, opt: string): boolean => {
  const v = a[id]?.value;
  return Array.isArray(v) && v.includes(opt);
};

